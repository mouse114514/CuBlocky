        foreach (var st in statuses)
        {
            var cls = StatusClassName(st.Id);
            var intensity = st.Type == "buff" ? "5" : "2";
            var iconExpr = ResolveStatusIconExpr(st, bp);
            sb.AppendLine();
            sb.AppendLine($"        [HarmonyPatch(typeof(Body), \"Update\")]");
            sb.AppendLine("        [HarmonyPostfix]");
            sb.AppendLine($"        public static void Tick_{cls}(Body __instance)");
            sb.AppendLine("        {");
            sb.AppendLine($"            var st = __instance.GetStatus<{cls}>();");
            sb.AppendLine("            if (st.Level > 0f)");
            sb.AppendLine("            {");
            sb.AppendLine("                st.RemainingSeconds -= Time.deltaTime;");
            sb.AppendLine("                if (st.RemainingSeconds < 0f)");
            sb.AppendLine("                {");
            sb.AppendLine("                    st.Level = 0f;");
            sb.AppendLine("                    st.RemainingSeconds = 0f;");
            sb.AppendLine("                }");
            sb.AppendLine("            }");
            sb.AppendLine("            if (st.Level > 0f && st.RemainingSeconds > 0f)");
            sb.AppendLine("            {");
            sb.AppendLine($"                MoodleRegistry.AddMoodle({intensity}, {iconExpr}, \"{Escape(st.FullName)}\", \"{Escape(st.Description)}\", important: true, key: \"{Escape(guid)}.{Escape(st.Id)}\");");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }
        // Placeholder icon helper if any status has no sprite
        if (statuses.Any(st => string.IsNullOrEmpty(ResolveSpriteName(st.SpriteAssetId, bp))))
        {
            sb.AppendLine();
            sb.AppendLine("        private static Sprite StatusPlaceholderSprite(Color color)");
            sb.AppendLine("        {");
            sb.AppendLine("            int size = 16;");
            sb.AppendLine("            var tex = new Texture2D(size, size, TextureFormat.RGBA32, false);");
            sb.AppendLine("            var pixels = new Color[size * size];");
            sb.AppendLine("            for (int i = 0; i < pixels.Length; i++) pixels[i] = color;");
            sb.AppendLine("            tex.SetPixels(pixels);");
            sb.AppendLine("            tex.Apply();");
            sb.AppendLine("            return Sprite.Create(tex, new Rect(0, 0, size, size), new Vector2(0.5f, 0.5f), 16f);");
            sb.AppendLine("        }");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
        return sb.ToString();
    }

    private static string StatusClassName(string id)
    {
        return "Status_" + SafeIdent(id);
    }

    private static string ResolveStatusIconExpr(StatusEntry st, Blueprint bp)
    {
        var spriteName = ResolveSpriteName(st.SpriteAssetId, bp);
        if (!string.IsNullOrEmpty(spriteName))
            return $"LoadSprite(\"{Escape(CleanSpriteName(spriteName))}\")";
        // No icon: colored placeholder by type (green buff / red debuff)
        var color = st.Type == "buff" ? "new Color(0.3f, 0.8f, 0.4f)" : "new Color(0.9f, 0.3f, 0.3f)";
        return $"StatusPlaceholderSprite({color})";
    }

    // ── helpers ───────────────────────────────────────────────────
    private static string ResolveSpriteName(string assetId, Blueprint bp)
    {
        if (!string.IsNullOrEmpty(assetId))
        {
            // Try to find in bp.Assets first
            var asset = bp.Assets.FirstOrDefault(a => a.Id == assetId);
            if (asset != null) return asset.Name;
            // If not in Assets, treat the asset ID as the filename directly
            return assetId;
        }
        return "";
    }

    private static string F(float v) => v.ToString("0.###", CultureInfo.InvariantCulture);
    private static string B(bool v) => v ? "true" : "false";
    private static string Cap(string s) => string.IsNullOrEmpty(s) ? "Tools" : char.ToUpperInvariant(s[0]) + s.Substring(1).ToLowerInvariant();
    private static string Escape(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", " ").Replace("\n", " ");
    private static string CleanSpriteName(string s)
    {
        if (string.IsNullOrEmpty(s)) return s;
        s = s.Trim().Trim('"', '\'');
        return s;
    }
    private static string SafeIdent(string s)
    {
        var sb = new StringBuilder();
        foreach (var c in s)
            if (char.IsLetterOrDigit(c)) sb.Append(c); else sb.Append('_');
        if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, "M");
        return sb.ToString();
    }

    private static string EmitBuilding(BuildingEntry b)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"            BuildingEntityRegistry.Register(\"{Escape(b.Id)}\", new CustomBuildingEntityDefinition {{");
        sb.AppendLine($"                Name = \"{Escape(b.Name)}\",");
        sb.AppendLine($"                Description = \"{Escape(b.Desc)}\"");
        sb.AppendLine("            });");
        sb.AppendLine();
        return sb.ToString();
    }

    private static string EmitTile(TileEntry t)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"            TileRegistry.Register(\"{Escape(t.Id)}\", new CustomTileDefinition {{");
        sb.AppendLine($"                Name = \"{Escape(t.Name)}\"");
        sb.AppendLine("            });");
        sb.AppendLine();
        return sb.ToString();
    }

    private static string EmitLocale(LocaleEntry l)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"            LocaleRegistry.Register(\"{Escape(l.Type)}\", \"{Escape(l.Id)}\", \"{Escape(l.Zh)}\");");
        sb.AppendLine($"            LocaleRegistry.Register(\"{Escape(l.Type)}\", \"{Escape(l.Id)}dsc\", \"{Escape(l.En)}\");");
        sb.AppendLine();
        return sb.ToString();
    }
