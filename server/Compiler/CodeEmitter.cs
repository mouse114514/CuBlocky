        sb.AppendLine($"                color = new Color({l.ColorR}f, {l.ColorG}f, {l.ColorB}f),");
        sb.AppendLine($"                valuePerLiter = {l.ValuePerLiter}f,");
        if (l.HealthUsable)
            sb.AppendLine($"                healthUsable = true,");
